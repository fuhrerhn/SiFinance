"""Generate v2-compatible Dart row types from an applied PostgreSQL schema."""

import json
from pathlib import Path
import subprocess
import sys


DART_TYPES = {
    "bigint": "int",
    "boolean": "bool",
    "date": "String",
    "numeric": "num",
    "text": "String",
    "timestamp with time zone": "String",
    "uuid": "String",
}

query = """
select json_agg(row_to_json(fields) order by table_name, ordinal_position)
from (
  select table_name, column_name, data_type, is_nullable, ordinal_position
  from information_schema.columns
  where table_schema = 'public'
    and table_name in ('akun', 'kategori', 'transaksi', 'budget', 'family_group', 'sesi_ai_chatbot', 'chat')
) fields
"""

columns = json.loads(subprocess.check_output(
    ["psql", "-XAt", "-v", "ON_ERROR_STOP=1", sys.argv[1], "-c", query],
    text=True,
))
tables = {}
for column in columns or []:
    tables.setdefault(column["table_name"], []).append(column)
if set(tables) != {"akun", "kategori", "transaksi", "budget", "family_group", "sesi_ai_chatbot", "chat"}:
    sys.exit("Apply the Personal Dashboard migrations before generating Dart types.")

parts = ["// Generated by scripts/generate_supabase_types.py. Do not edit.\n"]
for table, fields in tables.items():
    class_name = "".join(word.title() for word in table.split("_"))
    parts.append(f"extension type {class_name}Row(Map<String, dynamic> json) {{")
    parts.append(f"  static const table = '{table}';\n")
    for field in fields:
        name = field["column_name"]
        first, *rest = name.split("_")
        getter = first + "".join(word.title() for word in rest)
        kind = DART_TYPES[field["data_type"]]
        if field["is_nullable"] == "YES":
            kind += "?"
        parts.append(f"  {kind} get {getter} => json['{name}'] as {kind};")
    parts.append("}\n")

root = Path(__file__).resolve().parent.parent
(root / "lib/core/supabase/generated/database.g.dart").write_text("\n".join(parts))
