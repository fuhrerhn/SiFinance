alter table public.profiles rename to akun;
alter table public.categories rename to kategori;
alter table public.transactions rename to transaksi;
alter table public.budgets rename to budget;

create table public.family_group (
  id bigint generated by default as identity primary key,
  kode_qr text not null unique,
  tautan_undangan text not null unique
);

alter table public.akun
  add column family_group_id bigint references public.family_group(id) on delete set null,
  add column sembunyikan_pengeluaran_pribadi boolean not null default true,
  add column samarkan_catatan_detail boolean not null default true,
  add column bagikan_aktivitas_transaksi boolean not null default false;

alter table public.transaksi
  add column transaksi_pribadi boolean not null default true,
  drop constraint transactions_user_id_fkey,
  add constraint transaksi_akun_fkey foreign key (user_id) references public.akun(id) on delete cascade;

alter table public.budget
  drop constraint budgets_user_id_fkey,
  add constraint budget_akun_fkey foreign key (user_id) references public.akun(id) on delete cascade;

create table public.sesi_ai_chatbot (
  sesi_id uuid primary key default gen_random_uuid(),
  akun_id uuid not null references public.akun(id) on delete cascade,
  waktu_mulai timestamptz not null default now()
);

create table public.chat (
  id uuid primary key default gen_random_uuid(),
  sesi_id uuid not null references public.sesi_ai_chatbot(sesi_id) on delete cascade,
  waktu_kirim timestamptz not null default now(),
  pesan text not null,
  lampiran text,
  pengirim text not null check (pengirim in ('user', 'assistant'))
);

create index akun_family_group_idx on public.akun(family_group_id);
create index sesi_ai_chatbot_akun_idx on public.sesi_ai_chatbot(akun_id);
create index chat_sesi_waktu_idx on public.chat(sesi_id, waktu_kirim);

alter table public.family_group enable row level security;
alter table public.sesi_ai_chatbot enable row level security;
alter table public.chat enable row level security;

revoke all on public.family_group, public.sesi_ai_chatbot, public.chat from public, anon, authenticated;
grant select on public.family_group to authenticated;
grant select, insert, update, delete on public.sesi_ai_chatbot, public.chat to authenticated;
grant select, insert, update, delete on public.family_group, public.sesi_ai_chatbot, public.chat to service_role;

-- Membership is assigned by a trusted backend. Prevent clients from assigning themselves a group.
revoke insert, update on public.akun from authenticated;
grant insert (id, full_name, avatar_url),
      update (full_name, avatar_url, sembunyikan_pengeluaran_pribadi,
              samarkan_catatan_detail, bagikan_aktivitas_transaksi)
on public.akun to authenticated;

create policy family_group_member_read on public.family_group for select to authenticated
using (id = (select family_group_id from public.akun where id = (select auth.uid())));

create policy sesi_ai_chatbot_manage_own on public.sesi_ai_chatbot for all to authenticated
using (akun_id = (select auth.uid())) with check (akun_id = (select auth.uid()));

create policy chat_manage_own on public.chat for all to authenticated
using (exists (
  select 1 from public.sesi_ai_chatbot
  where sesi_ai_chatbot.sesi_id = chat.sesi_id and akun_id = (select auth.uid())
))
with check (exists (
  select 1 from public.sesi_ai_chatbot
  where sesi_ai_chatbot.sesi_id = chat.sesi_id and akun_id = (select auth.uid())
));

create or replace function private.create_profile()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.akun (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', ''));
  return new;
end;
$$;

-- Read-only PostgREST computed field for the CDR's total_terpakai.
create function public.total_terpakai(p_budget public.budget)
returns numeric language sql stable security invoker set search_path = '' as $$
  select coalesce(sum(t.amount), 0)
  from public.transaksi t
  where t.user_id = p_budget.user_id
    and t.category_id = p_budget.category_id
    and t.type = 'expense'
    and t.transaction_date between p_budget.start_date and p_budget.end_date;
$$;

revoke all on function public.total_terpakai(public.budget) from public, anon;
grant execute on function public.total_terpakai(public.budget) to authenticated, service_role;
